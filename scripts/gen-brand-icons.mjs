// Generates src/lib/brand-icons.ts from the simple-icons package (CC0).
// Run: npm i --no-save simple-icons && node scripts/gen-brand-icons.mjs
// Only the icons listed below are bundled. Brand names and logos belong to
// their owners and are used only to show which tools a skill refers to.
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

// slug -> extra names a skill might be written as
const LIST = {
  figma: [], python: [], php: [], javascript: ["js"], typescript: ["ts"], html5: ["html"], css: ["css3"],
  flask: [], tailwindcss: ["tailwind"], mysql: [], phpmyadmin: [], apachenetbeanside: ["netbeans"], jupyter: ["jupyter notebook"],
  gitkraken: [], postman: [], laravel: [], git: [], github: [], gitlab: [], jira: [], confluence: [], diagramsdotnet: ["draw.io", "drawio"],
  miro: [], notion: [], swagger: [], bootstrap: [], nodedotjs: ["node", "nodejs"], react: ["reactjs"], nextdotjs: ["next.js", "nextjs"],
  vuedotjs: ["vue", "vuejs"], angular: [], firebase: [], android: [], androidstudio: [], kotlin: [], dart: [], flutter: [],
  supabase: [], postgresql: ["postgres"], mariadb: [], mongodb: [], sqlite: [], redis: [], docker: [], linux: [], ubuntu: [],
  trello: [], clickup: [], asana: [], slack: [], wordpress: [], dbeaver: [], c: [], cplusplus: ["c++"], go: ["golang"],
  ruby: [], django: [], fastapi: [], spring: ["spring boot"], dotnet: [".net"], vercel: [], npm: [], vite: [], json: [],
  sap: [], salesforce: [], tableau: [], googlecloud: [], googlesheets: [], openai: [], blender: [], unity: [],
};

const lum = (hex) => {
  const n = parseInt(hex, 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};

const out = [];
for (const [slug, aliases] of Object.entries(LIST)) {
  const key = "si" + slug[0].toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) {
    console.warn("missing", slug);
    continue;
  }
  const L = lum(icon.hex);
  out.push({ t: icon.title, h: icon.hex, p: icon.path, a: aliases, d: L < 0.06 ? 1 : 0, l: L > 0.7 ? 1 : 0 });
}

const body = `// Generated by scripts/gen-brand-icons.mjs from simple-icons (CC0). Do not edit by hand.
// t: title, h: brand hex, p: 24x24 path, a: aliases, d: too dark for dark mode, l: too light for light mode.
export type BrandIcon = { t: string; h: string; p: string; a: string[]; d: 0 | 1; l: 0 | 1 };
export const BRAND_ICONS: BrandIcon[] = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../src/lib/brand-icons.ts", import.meta.url), body);
console.log("wrote", out.length, "icons");
